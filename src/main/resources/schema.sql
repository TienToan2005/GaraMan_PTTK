CREATE TABLE IF NOT EXISTS tblImportDetail6 (
  id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  quantity INT NOT NULL,
  unitPrice FLOAT NOT NULL,
  tblImportReceipt6id INT NOT NULL,
  tblAccessory6id INT NOT NULL,
  FOREIGN KEY (tblImportReceipt6id) REFERENCES tblImportReceipt6(id),
