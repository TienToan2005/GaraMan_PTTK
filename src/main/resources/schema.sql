CREATE TABLE IF NOT EXISTS tblMember6 (
  id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(100) NOT NULL,
  fullName VARCHAR(100) NOT NULL,
  phone VARCHAR(20),
  email VARCHAR(100),
  address VARCHAR(255)
);
CREATE TABLE IF NOT EXISTS tblCustomer6 (
  tblMember6id INT PRIMARY KEY,
  FOREIGN KEY (tblMember6id) REFERENCES tblMember6(id)
);
CREATE TABLE IF NOT EXISTS tblStaff6 (
  tblMember6id INT PRIMARY KEY,
  position VARCHAR(100),
  FOREIGN KEY (tblMember6id) REFERENCES tblMember6(id)
);
CREATE TABLE IF NOT EXISTS tblManager6 (
  tblMember6id INT PRIMARY KEY,
  FOREIGN KEY (tblMember6id) REFERENCES tblStaff6(tblMember6id)
);
