  tblServiceRequest6id INT NOT NULL,
  tblAccessory6id INT NOT NULL,
  FOREIGN KEY (tblServiceRequest6id) REFERENCES tblServiceRequest6(id),
  FOREIGN KEY (tblAccessory6id) REFERENCES tblAccessory6(id)
