  tblSupplier6id INT NOT NULL,
  tblInventoryStaff6id INT NOT NULL,
  FOREIGN KEY (tblSupplier6id) REFERENCES tblSupplier6(id),
  FOREIGN KEY (tblInventoryStaff6id) REFERENCES tblInventoryStaff6(tblMember6id)
