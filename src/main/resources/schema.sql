);
CREATE TABLE IF NOT EXISTS tblService6 (
  id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(255),
  price FLOAT
);
CREATE TABLE IF NOT EXISTS tblAccessory6 (
  id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(255),
  stock INT,
