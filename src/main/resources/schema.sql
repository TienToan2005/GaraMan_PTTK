  tblSalesStaff6id INT NOT NULL,
  FOREIGN KEY (tblServiceRequest6id) REFERENCES tblServiceRequest6(id),
  FOREIGN KEY (tblSalesStaff6id) REFERENCES tblSalesStaff6(tblMember6id)
